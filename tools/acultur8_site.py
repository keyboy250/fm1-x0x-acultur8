ROOT = Path(__file__).resolve().parents[1]
REPO = 'https://github.com/keyboy250/fm1-x0x-acultur8'
EMU_FILES = ('index.html', 'emu.css', 'emu.js', 'worklet.js', 'x0x.wasm',
             'slice-import.js', 'slice-ui.js', 'variant-ui.js', 'variant-ui.css', 'arrangement-ui.js', 'arrangement-ui.css',
             'BarlowSemiCondensed-Medium.ttf', 'manifest.json')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def demo(out):
    """An original deterministic percussion bank; no sampled or decoded source audio."""
    out.mkdir(parents=True, exist_ok=True)
    rate = 44100
    # Intact, differently sized tails packed consecutively; off-grid musical onsets.
    durations = (.38, .12, .28, .09, .31, .20)
    onsets = (0, .255, .735, 1.01, 1.26, 1.755)
    labels = ('Low pulse', 'Tick', 'Mid pulse', 'Tick two', 'Warm pulse', 'High pulse')
    samples, slices = [], []
    for k, (duration, onset, label) in enumerate(zip(durations, onsets, labels)):
        count, start = round(duration * rate), len(samples)
        for i in range(count):
            t = i / rate
            attack = min(1, i / 80)
            envelope = attack * math.exp(-7 * t / duration) * (1 - i / count)
            frequency = (70, 900, 180, 1200, 110, 330)[k]
            value = .45 * envelope * math.sin(2 * math.pi * frequency * t)
            samples.append(round(value * 32767))
        slices.append({'label': label, 'startSample': start, 'endSample': len(samples), 'time': onset})
    wav = out / 'acultur8-demo_slices.wav'
    with wave.open(str(wav), 'wb') as audio:
        audio.setparams((1, 2, rate, 0, 'NONE', 'not compressed'))
        audio.writeframes(struct.pack('<' + 'h' * len(samples), *samples))
    markers = {'version': 1, 'sampleRate': rate, 'channels': 1, 'audioFrames': len(samples),
               'bpm': 120, 'loopDuration': 2, 'audioSha256': digest(wav), 'slices': slices}
    (out / 'acultur8-demo_markers.json').write_text(json.dumps(markers, indent=2) + '\n', encoding='utf-8')
    (out / 'README.txt').write_text(
        'Acultur8 original synthetic demo, generated by tools/acultur8_site.py.\n'
        'GPL-3.0-only, as distributed with this project. No REX or sampled source audio.\n'
        '120 BPM, four quarter-note beats, six unequal original onsets.\n'
        'The WAV stores intact slice tails end to end. JSON stores musical trigger times.\n'
        'Load both files in the emulator. Switch on; choose Play with FM1 to sync.\n', encoding='utf-8')


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links, self.ids = [], set()

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            self.ids.add(attrs['id'])
        for name in ('src', 'href'):
            if attrs.get(name):
                self.links.append(attrs[name])


def validate_site(out):
    """Resolve local navigation as it would work below /repository-name/."""
    out = out.resolve()
    pages = {}
    for path in out.rglob('*.html'):
        parser = Links()
        parser.feed(path.read_text('utf-8'))
        pages[path] = parser
    for path, parser in pages.items():
        for link in parser.links:
            url = urlsplit(link)
            if url.scheme or url.netloc:
                continue
            if url.path.startswith('/'):
                raise ValueError(f'Root-relative URL breaks project hosting: {path.name}: {link}')
            target = (path.parent / unquote(url.path)).resolve() if url.path else path
            if not target.is_relative_to(out):
                raise ValueError(f'Link escapes site: {link}')
            if target.is_dir():
                target /= 'index.html'
            if not target.is_file():
                raise ValueError(f'Missing site target: {path.name}: {link}')
            if url.fragment and target in pages and unquote(url.fragment) not in pages[target].ids:
                raise ValueError(f'Missing site anchor: {path.name}: {link}')
    for path in out.rglob('*.css'):
        for link in re.findall(r'url\([\"\']?([^\)\"\']+)', path.read_text('utf-8')):
            if ':' in link:
                continue
            target = (path.parent / link).resolve()
            if link.startswith('/') or not target.is_relative_to(out) or not target.is_file():
                raise ValueError(f'Invalid CSS asset: {path.name}: {link}')
    forbidden = {'.rx2', '.rex', '.rcy', '.dll', '.fwsc', '.exe', '.py', '.zip'}
    for path in out.rglob('*'):
        if path.is_symlink() or path.suffix.lower() in forbidden or path.name.lower() in {'sdk', '.git', 'data'}:
            raise ValueError(f'Unexpected public artifact: {path.relative_to(out)}')
    return len(pages)


def package(out, emu=None):
    emu = (emu or ROOT / 'build/emu').resolve()
    out = out.resolve()
    # Never recursively replace a caller-selected folder. Build output must be new/empty.
    if out.exists() and any(out.iterdir()):
        raise ValueError(f'Output must be empty: {out}')
    spec = importlib.util.spec_from_file_location('acultur8_builder', ROOT / 'lab/build_emulator.py')
    sys.path.insert(0, str(ROOT / 'lab'))
    builder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(builder)
    for name in EMU_FILES:
        if not (emu / name).is_file():
            raise ValueError(f'Missing emulator artifact: {name}; run the required checks/build first')
    manifest = json.loads((emu / 'manifest.json').read_text('utf-8'))
    if manifest['source_sha256'] != builder.source_hash(ROOT):
        raise ValueError('Emulator is stale: rebuild against current source before publishing')
    if manifest['wasm_sha256'] != digest(emu / 'x0x.wasm'):
        raise ValueError('Emulator WASM checksum does not match its build manifest')
    out.mkdir(parents=True, exist_ok=True)
    (out / 'emu').mkdir()
    for name in EMU_FILES:
        shutil.copy2(emu / name, out / 'emu' / name)
    html = (out / 'emu/index.html').read_text('utf-8')
    html = html.replace('href="/"', 'href="../"').replace('href="/faq"', 'href="../faq/"')
    html = html.replace('href="manual.txt"', 'href="../manual/"')
    html = html.replace('<nav>', '<nav><a href="../about/">About</a>', 1)
    html = html.replace('https://github.com/charlesvestal/fm1-x0x', REPO)
    html = html.replace('</body>', '<script type="module" src="public-demo.js"></script>\n</body>')
    (out / 'emu/index.html').write_text(html, encoding='utf-8')
    # Native converter handoff is intentionally unavailable on the public static site.
    slice_js = (out / 'emu/slice-ui.js').read_text('utf-8')
    marker = '// Local converter handoff:'
    if marker not in slice_js:
        raise ValueError('Expected local converter handoff boundary changed; review static packaging')
    slice_js = slice_js.split(marker, 1)[0] + "\nif(new URLSearchParams(location.search).has('rex')) { say('Raw REX handoff is local-only. Import the matching WAV and JSON files here.', true); }\n"
    (out / 'emu/slice-ui.js').write_text(slice_js, encoding='utf-8')
    templates = ROOT / 'web/acultur8'
    for name in ('index.html', 'site.css'):
        shutil.copy2(templates / name, out / name)
    for section in ('faq', 'manual', 'about'):
        (out / section).mkdir()
        shutil.copy2(templates / f'{section}.html', out / section / 'index.html')
    shutil.copy2(templates / 'public-demo.js', out / 'emu')
    shutil.copy2(ROOT / 'LICENSE', out / 'LICENSE.txt')
    shutil.copy2(ROOT / 'LICENSING.md', out / 'CREDITS.txt')
    shutil.copy2(ROOT / 'assets/fonts/Barlow-OFL.txt', out / 'emu/Barlow-OFL.txt')
    demo(out / 'demo')
    (out / '.nojekyll').write_text('', encoding='utf-8')
    # Create the linked manifest before validating navigation; exclude itself from hashes.
    (out / 'release-manifest.json').write_text('{}\n', encoding='utf-8')
    pages = validate_site(out)
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    dirty = bool(subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True).strip())
    files = {p.relative_to(out).as_posix(): digest(p) for p in sorted(out.rglob('*'))
             if p.is_file() and p.name != 'release-manifest.json'}
    (out / 'release-manifest.json').write_text(json.dumps({'kind': 'browser-alpha', 'commit': revision,
        'workingTreeDirty': dirty, 'emulator': manifest, 'files': files}, indent=2) + '\n', encoding='utf-8')
    print(f'Browser alpha: {out} ({pages} pages, {len(files)} checksummed files)')
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='New or empty destination; defaults to a unique build/site-* folder')
    parser.add_argument('--emulator', type=Path)
    args = parser.parse_args()
    (ROOT / 'build').mkdir(exist_ok=True)
    output = args.output or Path(tempfile.mkdtemp(prefix='site-', dir=ROOT / 'build'))
    package(output, args.emulator)


if __name__ == '__main__':
    main()
