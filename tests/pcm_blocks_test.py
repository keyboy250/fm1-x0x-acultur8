"""Compare production cymbal codec/accessor against original PCM and known G.711 vectors.
DSP parity oracles use decoded samples; this check separately measures codec loss.
"""
import json,math,subprocess,sys,tempfile
from pathlib import Path
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'tools'));import gen_drum_samples as codec
assert [(v,codec.mulaw_enc(v)) for v in (0,1,-1,32767,-32768)]==[(0,255),(1,255),(-1,127),(32767,128),(-32768,0)]
assert [(u,codec.mulaw_dec(u)) for u in (0,127,128,255)]==[(0,-32124),(127,0),(128,32124),(255,0)]
with tempfile.TemporaryDirectory() as tmp:
 tmp=Path(tmp); checks=[]
 for name,filename in codec.SAMPLES:
  pcm,_=codec.read_wav(root/'assets/909'/filename)
  decoded=[codec.mulaw_dec(codec.mulaw_enc(v)) for v in pcm]
  energy=sum(v*v for v in pcm);error=sum((a-b)**2 for a,b in zip(pcm,decoded))
  snr=10*math.log10(energy/error);peak=max(abs(a-b) for a,b in zip(pcm,decoded))
  assert snr>35 and peak<=1024,(filename,snr,peak)
  expected=','.join(map(str,decoded))
  checks.append('static const int16_t '+name+'_expected[]={'+expected+'};')
  checks.append('static void check_'+name+'(void){for(unsigned i=0;i<'+str(len(pcm))+';i++)assert(x0x_mulaw['+name+'[i]]=='+name+'_expected[i]);}')
  print(json.dumps({'sample':filename,'frames':len(pcm),'codec_snr_db':snr,'max_error_int16':peak,'lossless':False}))
 source='#include <assert.h>\n#include <stdint.h>\n#include "x0x_drum_samples.h"\n'+'\n'.join(checks)+'\nint main(void){'+''.join('check_'+n+'();' for n,_ in codec.SAMPLES)+'}\n'
 (tmp/'codec.c').write_text(source)
 subprocess.run(['cc','-std=c99','-O1','-g','-fsanitize=address,undefined','-I'+str(root/'build/gen'),str(tmp/'codec.c'),'-o',str(tmp/'codec')],check=True)
 subprocess.run([str(tmp/'codec')],check=True)
 print('PASS actual generated byte samples/decode accessor: all cymbal frames, ASan/UBSan; original PCM loss measured separately')
